def profile_preview(draft):
    """把 Agent 从用户原文提取的字段草稿显示为已识别/待补充；不自己编造用户信息。"""
    def as_text(value):
        if isinstance(value, list):
            value = [x.get('description', '') if isinstance(x, dict) else x for x in value]
            return '、'.join(str(x) for x in value if x)
        if isinstance(value, dict):
            return '；'.join(f'{key}：{as_text(val)}' for key,val in value.items() if as_text(val))
        return str(value or '').strip()
    fields = [('目标岗位（可多选）','target_roles'),('专业背景／项目／简历','background'),
              ('真实拥有的技能（多选）','confirmed_skills'),('工作年限','experience'),
              ('城市（可多选）','preferred_cities'),('期望薪资','expected_salary'),
              ('优先条件（可多选）','priority_conditions'),('一票否决条件（可多选）','hard_reject_rules'),
              ('职责偏好与回避方向','role_preferences')]
    output=['## 第2步｜你的画像信息核对',
            '以下仅来自你已提供的文字；**已识别的选项会保留，不要求重复填写**。请确认或修正：']
    for label,key in fields:
        txt=as_text(draft.get(key))
        output.append(f'- **{label}**：'+ (f'**已识别：{txt}**' if txt and txt not in {'未提及','未知','待确认'} else '**待补充**'))
    stress={'strong':'强','average':'一般','weak':'弱'}.get(draft.get('stress_tolerance'))
    output.extend(['','## 第3步｜抗压能力（单选）',
                   '请从 **强 / 一般 / 弱** 中选一个。'+(f' 当前已识别：**{stress}**（请确认）' if stress else ' **待补充**。'),
                   '确认后执行；如果抗压弱且JD对候选人有明确原文要求，最终分减1（最低2，不变成硬性红线）。'])
    return '\n'.join(output)+'\n'
